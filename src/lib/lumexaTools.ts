// Client for the backend's lighter design endpoints: balance what-ifs, aerodynamics, parametric shapes, crankshaft.
// None of them needs the CAD kernel except to run the scripts they return, so they answer quickly.

async function post<T>(path: string, body: unknown, timeoutMs = 60000): Promise<T> {
  const ctl = new AbortController();
  const t = setTimeout(() => ctl.abort(), timeoutMs);
  try {
    const res = await backendFetch(path, {
      method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body), signal: ctl.signal,
    });
    const text = await res.text();
    if (!res.ok) {
      let msg = text;
      try { const j = JSON.parse(text); msg = typeof j.detail === 'string' ? j.detail : JSON.stringify(j.detail ?? j); } catch { /* plain text */ }
      throw new Error(msg.slice(0, 300) || `${path} failed (${res.status})`);
    }
    return JSON.parse(text) as T;
  } catch (e) {
    if (e instanceof DOMException && e.name === 'AbortError') throw new Error('The backend did not answer in time (is it running?).');
    throw e;
  } finally { clearTimeout(t); }
}

