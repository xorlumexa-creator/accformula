/** Multipart upload (read once on the server, no base64 doubling of the file in memory). */
export async function checkSkin(file: File, interfaces: SkinInterface[], geometryHash: string, params: Record<string, number> = {}): Promise<SkinReport> {
  const fd = new FormData();
  fd.append('file', file);
  fd.append('graph', JSON.stringify({ interfaces }));
  fd.append('params', JSON.stringify(params));
  fd.append('geometry_hash', geometryHash);
  const ctl = new AbortController();
  const t = setTimeout(() => ctl.abort(), 240000);
  try {
    const res = await backendFetch('/skin-check', { method: 'POST', body: fd, signal: ctl.signal });
    const text = await res.text();
    if (!res.ok) {
      let msg = text;
      try { const j = JSON.parse(text); msg = typeof j.detail === 'string' ? j.detail : JSON.stringify(j.detail ?? j); } catch { /* plain text */ }
      throw new Error(msg.slice(0, 400) || `skin check failed (${res.status})`);
    }
    return JSON.parse(text) as SkinReport;
  } catch (e) {
    if (e instanceof DOMException && e.name === 'AbortError') throw new Error('The skin check took too long (is the backend busy?).');
    throw e;
  } finally { clearTimeout(t); }
}
